<?php
namespace Controllers;
require_once $base_path . 'modules/helpers.php';

/*
	Задачи базового контроллера:
 	* 1. Управлять сессией и текущим пользователем
	* 2. Передавать данные о пользователе в шаблоны
 	* 3. Подготавливать и отображать страницы (рендеринг)

*/

class BaseController {

	/*	
	 * Свойство хранит данные о текущем залогиненном пользователе
	 * Доступно во всех контроллерах-наследниках
	
	 * Структура: массив из БД с полями id, name, email и т.д.
	 * Если никто не залогинен → NULL
	*/

	public $current_user=NULL;


	// Метод добавляет информацию о пользователе в массив $context

	protected function context_append(array &$context){

		$context['__current_user'] = $this->current_user;
	}
	
	protected function render(string $template, array $context){
		$this->context_append($context);

		// Вызываем функцию render() из пространства имён Helpers
		// Она подключает нужный файл шаблона

		\Helpers\render($template, $context);
	}


	/*
	    КОНСТРУКТОР — вызывается автоматически при создании объекта контроллера
	    Задача конструктора — подготовить всё для работы контроллера:
	 *   1. Запустить/проверить сессию
	 *   2. Найти текущего пользователя (если он залогинен)
	 *   3. Записать данные о нём в свойство $current_user

	*/

	function __construct(){

		//Проеверяем текущее состояние сессии, если не запущена(не активна) - запускаем
		if(session_status() != PHP_SESSION_ACTIVE)

			//Запускаем сессию — теперь можем работать с $_SESSION
			// Сессия хранит данные между запросами одного пользователя
			session_start();


		//ПОИСК ЗАЛОГИНЕННОГО ПОЛЬЗОВАТЕЛЯ
		//$_SESSION['current_user'] сохраняется при успешном входе (в контроллере Login)

		if(isset($_SESSION['current_user'])) {

			// Если в сессии есть ID пользователя — ищем его в базе данных
			// Создаём объект модели User(она отвечает за работу с таблицей users)
			$users = new \Models\User();

			/*
			     get_or_404() — получает пользователя по ID из базы
				Если не находит — выбрасывает ошибку 404
				 Результат — массив с данными пользователя (id, name, email, password...)

			*/
			$this->current_user = $users->get_or_404($_SESSION['current_user']);
			}
		else

			/*
				 ОЧИСТКА "МЁРТВЫХ" СЕССИЙ ==========
			
			 Если в сессии нет записи 'current_user', значит никто не залогинен
			 Вызываем session_destroy() для очистки сессии
			
			 Бывают "мусорные" сессии — без данных, но занимающие память
			 Это безопасно: если пользователь не залогинен — его сессия не нужна
			 При следующем посещении создастся новая чистая сессия
			
			*/

			session_destroy();

	}
}